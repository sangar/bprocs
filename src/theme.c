size_t theme_count(void)
{
    return countof(THEMES);
}

const Theme *theme_at(size_t index)
{
    return &THEMES[index % countof(THEMES)];
}

bool theme_find(String name, size_t *index)
{
    for (size_t i = 0; i < countof(THEMES); i++) {
        if (str_equal(name, S(THEMES[i].name))) {
            *index = i;
            return true;
        }
    }
    return false;
}
