static bool in_ranges(const Range *ranges, size_t count, uint32_t codepoint)
{
    size_t low = 0;
    size_t high = count;
    while (low < high) {
        size_t mid = low + (high - low) / 2;
        if (codepoint < ranges[mid].first) {
            high = mid;
        } else if (codepoint > ranges[mid].last) {
            low = mid + 1;
        } else {
            return true;
        }
    }
    return false;
}

int glyph_width(uint32_t codepoint)
{
    if (codepoint < 0x300) {
        return 1;
    }
    if (in_ranges(ZERO_WIDTH, countof(ZERO_WIDTH), codepoint)) {
        return 0;
    }
    return in_ranges(WIDE, countof(WIDE), codepoint) ? 2 : 1;
}
